    /**
     * Saves whatever's currently in the editor. A line (or per-line
     * {@code {chars N}} override, or a widget's own {@code limit=}) longer
     * than its character limit is no longer rejected here — it's simply
     * let through and saved as-is, warning the editor in chat that it'll
     * show up truncated. The actual truncation happens where it always
     * has, at render time (see {@code NametagManager#computeFullText} for
     * line limits and {@code NametagManager#parseFormat} for widget
     * limits) — the up-front check here could only ever verify against
     * placeholder values known at the moment of saving anyway, and a
     * placeholder like {@code %luckperms_prefix%} can legitimately expand
     * to a different length later, so blocking the save outright never
     * actually guaranteed anything past that first render.
     */
    private void confirm(Player p,Session s) {
        String raw=serialize(s); boolean ownFormat=s.target==Target.PLAYER_EDIT;
        if(raw.isEmpty()){p.sendMessage(ChatColor.RED+"Your nametag format cannot be empty.");return;}
        int characterLimit=ownFormat?NametagFormatPermissions.effectiveLineCharacterLimit(config,p):s.target==Target.PLAYER?characterLimit(s.targetId):-1;
        int[] characterOverrides=TemplateMarkers.lineCharacterOverrides(raw);
        Player contextPlayer=ownFormat?p:(s.target==Target.PLAYER?Bukkit.getPlayer(UUID.fromString(s.targetId)):p);
        if(contextPlayer!=null){
            List<String> plainLines=new ArrayList<>();
            for(Component line:afx.customplayernametags.format.NametagFormatter.splitLines(afx.customplayernametags.format.NametagFormatter.toComponent(manager.parseFormat(contextPlayer,raw))))
                plainLines.add(afx.customplayernametags.format.NametagFormatter.plainText(line));
            for(int i=0;i<plainLines.size();i++){
                int lineCharLimit=i<characterOverrides.length&&characterOverrides[i]>=0?characterOverrides[i]:characterLimit;
                if(lineCharLimit>=0&&plainLines.get(i).length()>lineCharLimit){
                    p.sendMessage(ChatColor.YELLOW+"Line "+(i+1)+" is over its "+lineCharLimit+" character limit once placeholders and colors are resolved — it'll be shown truncated.");
                }
            }
        }
        if(s.target==Target.PLAYER_EDIT) {
            UUID uuid=p.getUniqueId();
            // A player editing their own applied format can only ever touch Widget slots
            // (see lockedForPlayer) — so unless they already have an explicit individual
            // override on file (in which case that override is still saved as a whole, same
            // as before), what they just did is fill in widget(s) inside an inherited
            // global/group format. That gets persisted separately, keyed by widget position,
            // instead of forking their whole effective format into a brand-new override —
            // see NametagManager#saveWidgetFills and PlayerWidgetFillStore.
            if(manager.hasIndividualFormatOverride(uuid)) manager.setFormatOverride(uuid,raw);
            else manager.saveWidgetFills(uuid,TemplateMarkers.extractWidgetContents(raw));
            sessions.remove(uuid);p.closeInventory();messages.send(p,"format-set-self-success");return;
        }
        switch(s.target){case GLOBAL->{if(s.bedrock)config.setBedrockGlobalFormat(raw);else config.setGlobalFormat(raw);manager.refreshAll();}case PLAYER->{manager.setFormatOverride(UUID.fromString(s.targetId),raw);notifyPlayerFormatChanged(p,s.targetId,raw);}case GROUP->{manager.getGroupFormatStore().set(s.targetId,raw,s.bedrock);manager.refreshAll();}default->{}}
        sessions.remove(p.getUniqueId());p.closeInventory();p.sendMessage(ChatColor.GREEN+"Updated nametag format.");
    }
