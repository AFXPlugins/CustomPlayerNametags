        if(s.scrollRow>maxScrollRow)s.scrollRow=maxScrollRow; if(s.scrollRow<0)s.scrollRow=0;
        int maxLineLength=0; for(Row r:rows) maxLineLength=Math.max(maxLineLength,r.indices().size());
