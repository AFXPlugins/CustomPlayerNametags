    private static List<Chunk> parse(String raw){List<Chunk> out=new ArrayList<>();if(raw==null)return out;Matcher m=TOKEN.matcher(raw);int last=0;while(m.find()){if(m.start()>last)out.add(new Chunk(Kind.TEXT,raw.substring(last,m.start())));out.add(parseToken(m.group()));last=m.end();}if(last<raw.length())out.add(new Chunk(Kind.TEXT,raw.substring(last)));return out;}
    /** Builds the right {@link Chunk} (kind + any nested widget data) for one already-matched {@link #TOKEN} match. */
    private static Chunk parseToken(String x){
        if(x.equals("\\n")||x.equals("\n"))return new Chunk(Kind.NEWLINE,"\\n");
        if(x.startsWith(TemplateMarkers.WIDGET_OPEN_PREFIX)){
            Chunk widget=new Chunk(Kind.WIDGET,x);
            TemplateMarkers.Widget parsed=TemplateMarkers.parseWidget(x);
            // Carried straight through from the tag rather than regenerated — this is what keeps
            // a player's already-stored fill (keyed by this same id, see PlayerWidgetFillStore)
            // attached to this widget across edit sessions. Every widget reaching here should
            // already have an id (ConfigManager/GroupFormatStore/PlayerFormatStore all run
            // TemplateMarkers#ensureWidgetIds on load), but mint one on the spot as a fallback
            // rather than ever leaving a widget id-less in the editor.
            widget.widgetId=parsed.id()==null||parsed.id().isEmpty()?TemplateMarkers.generateWidgetId():parsed.id();
            widget.widgetColors=parsed.colors();
            widget.widgetPlaceholders=parsed.placeholders();
            widget.widgetText=parsed.text();
            widget.widgetCharacterLimit=parsed.characterLimit();
            // Widget contents are only ever TEXT/COLOR/PLACEHOLDER chunks (never
            // newlines or another widget), so the outer tokenizer can safely
            // re-run over the inner raw string to reconstruct them.
            widget.widgetContents=parse(parsed.inner());
            return widget;
        }
        if(x.equals("{player}"))return new Chunk(Kind.PLACEHOLDER,x);
        if(x.startsWith("%"))return new Chunk(Kind.PLACEHOLDER,x);
        if(x.startsWith("&")||x.startsWith("<"))return new Chunk(Kind.COLOR,x);
        return new Chunk(Kind.TEXT,x);
    }
    private static String serialize(Session s){StringBuilder b=new StringBuilder();for(Chunk c:s.chunks)b.append(c.kind==Kind.NEWLINE?"\\n":c.value);return b.toString();}
    /**
     * Rebuilds a widget chunk's {@code value} (its {@link TemplateMarkers}
     * tag text) from its current flags and {@code widgetContents} —
     * must be called after any edit to either, or {@link #serialize} would
     * keep emitting the widget's stale pre-edit contents.
     */
    private static void resyncWidget(Chunk widget){
        StringBuilder inner=new StringBuilder();
        for(Chunk c:widget.widgetContents)inner.append(c.value);
        widget.value=TemplateMarkers.encodeWidget(widget.widgetId,widget.widgetColors,widget.widgetPlaceholders,widget.widgetText,widget.widgetCharacterLimit,inner.toString());
    }
    /**
     * One selectable entry on the "Select Color" page: {@code key} is its
     * gui.yml config key (e.g. {@code "dark_blue"}), {@code tag} is the
     * actual MiniMessage tag added to the format when clicked (e.g.
     * {@code "<dark_blue>"}) and never changes regardless of gui.yml, and
     * {@code fallbackSlot}/{@code fallbackMaterial}/{@code fallbackName} are
     * what's used if gui.yml doesn't override this entry.
     */
    private record ColorChoice(String key, String tag, int fallbackSlot, Material fallbackMaterial, String fallbackName) {}
    private static final List<ColorChoice> COLOR_CHOICES=createColorChoices();
    private static List<ColorChoice> createColorChoices(){
        // Deliberately omits <underlined>, <strikethrough>, and <reset> —
        // no longer offered as selectable colors/styles in the "Select
        // Color" editor menu. A format that already contains one of those
        // tags (set directly in config.yml, a preset, etc.) still renders
        // and parses exactly as before; only the picker no longer offers them.
        String[] tags={"<black>","<dark_blue>","<dark_green>","<dark_aqua>","<dark_red>","<dark_purple>","<gold>","<gray>","<dark_gray>","<blue>","<green>","<aqua>","<red>","<light_purple>","<yellow>","<white>","<bold>","<italic>","<obfuscated>","<rainbow>"};
        List<ColorChoice> out=new ArrayList<>();
        for(int i=0;i<tags.length;i++){
            String tag=tags[i]; String key=tag.substring(1,tag.length()-1);
            out.add(new ColorChoice(key,tag,i,materialFor(tag),ChatColor.WHITE+friendlyLabel(key)));
        }
        return out;
    }
    /**
     * Turns a colors-menu key like {@code "dark_red"} into a friendly
     * display label like {@code "Dark Red"} — purely cosmetic for the
     * "Select Color" picker. What actually gets added to the format when
     * clicked is always {@link ColorChoice#tag()} (e.g. {@code <dark_red>}),
     * so once it's in the editor grid it's shown as its raw tag again, same
     * as every other chunk.
     */
    private static String friendlyLabel(String key){
        StringBuilder out=new StringBuilder();
        for(String word:key.split("_")){
            if(word.isEmpty())continue;
            if(out.length()>0)out.append(' ');
            out.append(Character.toUpperCase(word.charAt(0))).append(word.substring(1));
        }
        return out.toString();
    }
