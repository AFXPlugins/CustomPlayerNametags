    /** Whether {@code p} only has read/widget-fill access to {@code s} — true for a non-admin player editing their own applied format (Target.PLAYER_EDIT), false for every other session and for any admin. */
    private boolean lockedForPlayer(Player p, Session s) {
        return s.target==Target.PLAYER_EDIT && !p.hasPermission("customplayernametags.admin");
    }
    /** Splits the format's chunks into logical lines (split on newline chunks). No longer wrapped across extra display rows — a line longer than one row scrolls horizontally instead (see {@link Session#scrollCol}). */
    private List<Row> computeRows(Session s) {
        List<List<Integer>> logical=new ArrayList<>(); logical.add(new ArrayList<>());
        for(int i=0;i<s.chunks.size();i++){ if(s.chunks.get(i).kind==Kind.NEWLINE){List<Integer> next=new ArrayList<>();next.add(i);logical.add(next);}else logical.get(logical.size()-1).add(i); }
        List<Row> rows=new ArrayList<>();
        for(List<Integer> line:logical) rows.add(new Row(line));
        return rows;
    }
    /** Renders one screen's worth of logical lines — rows s.scrollRow through s.scrollRow+VISIBLE_ROWS-1 — each windowed horizontally to chunks s.scrollCol through s.scrollCol+8. */
    private void renderChunks(Player p,Inventory inv,Session s,List<Row> rows) {
        boolean interactive=!lockedForPlayer(p,s);
        for(int r=0;r<VISIBLE_ROWS;r++) {
            int rowIndex=s.scrollRow+r; if(rowIndex>=rows.size())break;
            List<Integer> line=rows.get(rowIndex).indices();
            int take=Math.max(0,Math.min(ROW_WIDTH,line.size()-s.scrollCol));
            for(int n=0;n<take;n++){int index=line.get(s.scrollCol+n);int slot=r*9+n;s.displayed.put(slot,index);inv.setItem(slot,chunkItem(p,s.chunks.get(index),interactive));}
        }
    }
