    /** Renders the logical line containing chunk index {@code selected} across slots 0-8, windowed to keep {@code selected} visible if the line has more than 9 chunks. */
    private void renderDetailRow(Player p, Inventory inv, Session s, int selected) {
        List<Integer> line=null;
        for(Row r:computeRows(s)) if(r.indices().contains(selected)){line=r.indices();break;}
        if(line==null)return;
        int pos=line.indexOf(selected);
        int start=Math.max(0,Math.min(pos-ROW_WIDTH/2,Math.max(0,line.size()-ROW_WIDTH)));
        int take=Math.min(ROW_WIDTH,line.size()-start);
        for(int n=0;n<take;n++){
            int chunkIndex=line.get(start+n);
            inv.setItem(n,chunkPreviewItem(p,s.chunks.get(chunkIndex),chunkIndex==selected));
        }
    }
